-- Reservations table
CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              user_id BIGINT NOT NULL,
                              campaign_id BIGINT NOT NULL,
                              product_id BIGINT NOT NULL,

                              quantity INTEGER NOT NULL,

                              status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',

                              expires_at TIMESTAMPTZ NOT NULL,

                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_reservations_user
                                  FOREIGN KEY (user_id)
                                      REFERENCES users(id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT fk_reservations_inventory
                                  FOREIGN KEY (campaign_id, product_id)
                                      REFERENCES inventory(campaign_id, product_id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT chk_reservations_quantity
                                  CHECK (quantity > 0),

                              CONSTRAINT chk_reservations_status
                                  CHECK (
                                      status IN (
                                                 'ACTIVE',
                                                 'CONFIRMED',
                                                 'EXPIRED',
                                                 'CANCELLED'
                                          )
                                      )
);

-- Indexes
CREATE INDEX idx_reservations_user
    ON reservations(user_id);

CREATE INDEX idx_reservations_status_expires
    ON reservations(status, expires_at);

CREATE INDEX idx_reservations_inventory
    ON reservations(campaign_id, product_id);