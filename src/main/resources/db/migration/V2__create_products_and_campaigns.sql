-- Products table
CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(255) NOT NULL,
                          description TEXT,
                          sku VARCHAR(100) NOT NULL UNIQUE,
                          price NUMERIC(12, 2) NOT NULL,
                          active BOOLEAN NOT NULL DEFAULT TRUE,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT chk_products_price_positive
                              CHECK (price > 0)
);


-- Campaigns table
CREATE TABLE campaigns (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(255) NOT NULL,
                           description TEXT,
                           start_time TIMESTAMPTZ NOT NULL,
                           end_time TIMESTAMPTZ NOT NULL,
                           status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT chk_campaigns_valid_period
                               CHECK (end_time > start_time),

                           CONSTRAINT chk_campaigns_status
                               CHECK (status IN ('DRAFT', 'SCHEDULED', 'ACTIVE', 'COMPLETED', 'CANCELLED'))
);


-- Campaign products table
CREATE TABLE campaign_products (
                                   campaign_id BIGINT NOT NULL,
                                   product_id BIGINT NOT NULL,
                                   sale_price NUMERIC(12, 2) NOT NULL,
                                   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                   PRIMARY KEY (campaign_id, product_id),

                                   CONSTRAINT fk_campaign_products_campaign
                                       FOREIGN KEY (campaign_id)
                                           REFERENCES campaigns(id)
                                           ON DELETE CASCADE,

                                   CONSTRAINT fk_campaign_products_product
                                       FOREIGN KEY (product_id)
                                           REFERENCES products(id)
                                           ON DELETE RESTRICT,

                                   CONSTRAINT chk_campaign_products_sale_price
                                       CHECK (sale_price > 0)
);


-- Indexes
CREATE INDEX idx_products_active
    ON products(active);

CREATE INDEX idx_campaigns_status_period
    ON campaigns(status, start_time, end_time);

CREATE INDEX idx_campaign_products_product
    ON campaign_products(product_id);